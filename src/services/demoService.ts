export class DemoService {
  /**
   * Builds the initial ready timeline for a scenario
   */
  public createInitialTimeline(scenarioId: DemoScenarioId): DemoTimelineStep[] {
    const config = DEMO_SCENARIO_CONFIGS[scenarioId];
    return DEMO_TIMELINE_TEMPLATE.map((tmpl, idx) => ({
      ...tmpl,
      description: config.stages[idx]?.description || tmpl.description,
      metricHighlight: config.stages[idx]?.metricHighlight,
      status: 'pending',
    }));
  }

  /**
   * Retrieves the stage configuration for a given scenario and step (0 to 5)
   */
  public getStage(scenarioId: DemoScenarioId, stepIndex: number): DemoStageConfig {
    const config = DEMO_SCENARIO_CONFIGS[scenarioId];
    const clampedIndex = Math.max(0, Math.min(5, stepIndex));
    return config.stages[clampedIndex];
  }

  public getScenarioDetails(scenarioId: DemoScenarioId) {
    return DEMO_SCENARIO_CONFIGS[scenarioId];
  }
}

export const demoService = new DemoService();
